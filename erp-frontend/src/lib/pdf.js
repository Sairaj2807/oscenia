  doc.text(`NPWP         ${vendor?.npwp || '-'}`, 16, 69)
  doc.text(`PIC          ${vendor?.pic?.name || '-'}`, 16, 76)
  doc.text(`Size on file ${attachment.size || '-'}`, 16, 83)

  doc.setDrawColor(200, 150, 40)
  doc.setFillColor(255, 250, 235)
  doc.roundedRect(16, 96, 178, 34, 2, 2, 'FD')
  doc.setTextColor(150, 100, 20)
  doc.setFontSize(9)
