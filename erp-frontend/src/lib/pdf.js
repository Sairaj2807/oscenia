  doc.text(`Due          ${inv.due}`, 16, 76)

  // Status stamp
  doc.setDrawColor(...(inv.status === 'Paid' ? [40, 160, 100] : [200, 150, 40]))
  doc.setTextColor(...(inv.status === 'Paid' ? [40, 160, 100] : [200, 150, 40]))
  doc.setFontSize(16)
  doc.setFont('helvetica', 'bold')
  doc.roundedRect(150, 44, 44, 14, 2, 2)
  doc.text(inv.status.toUpperCase(), 172, 53, { align: 'center' })
  doc.setFont('helvetica', 'normal')

  // Line table
  let y = 96
  doc.setFillColor(...NAVY)
  doc.setTextColor(255, 255, 255)
  doc.rect(16, y - 6, 178, 9, 'F')
  doc.setFontSize(9)
  doc.text('DESCRIPTION', 20, y)
  doc.text('AMOUNT', 190, y, { align: 'right' })

  y += 12
  doc.setTextColor(60, 60, 60)
  doc.setFontSize(10)
  doc.text(`${inv.type} — ${projectName || inv.project}`, 20, y)
  doc.text(money(inv.amount), 190, y, { align: 'right' })

