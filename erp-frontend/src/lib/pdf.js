import { jsPDF } from 'jspdf'
import { getNumberLocale } from './format.js'

const NAVY = [10, 20, 36]
const GOLD = [198, 161, 91]
const GREY = [110, 120, 135]

// Follows the UI language: a document generated while the ERP is in Bahasa
// Indonesia should carry Indonesian separators.
function money(n) {
  return 'Rp ' + n.toLocaleString(getNumberLocale())
}

function header(doc, title) {
  doc.setFillColor(...NAVY)
  doc.rect(0, 0, 210, 34, 'F')
  doc.setTextColor(...GOLD)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(20)
  doc.text('OSCENIA', 16, 18)
  doc.setFontSize(7)
  doc.setTextColor(220, 220, 220)
  doc.text('EVENT PRODUCTION · JAKARTA', 16, 24)
  doc.setTextColor(...GOLD)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(13)
  doc.text(title, 194, 18, { align: 'right' })
}

function footer(doc, note) {
  doc.setDrawColor(...GOLD)
  doc.setLineWidth(0.3)
  doc.line(16, 278, 194, 278)
  doc.setFontSize(8)
  doc.setTextColor(...GREY)
  doc.text(note, 16, 284)
  doc.text('Generated by Oscenia ERP · prototype', 194, 284, { align: 'right' })
}

// Journal amounts print to two decimals — the first feedback round asked for
// `,00` on every accounting figure, and a voucher is the most accounting-facing
// document the system produces.
function money2(n) {
  return 'Rp ' + Number(n || 0).toLocaleString(getNumberLocale(), {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })
}

// ---------------------------------------------------------------------------
// Journal evidence printing (round 2)
//
// "Supports physical verification, signature authorization, and official
// archival filing." One generator covers all three document classes the client
// named, because the layout differs only in its title, its stamp and which
// counterparty block it carries:
//
//   cash-out  CASH DISBURSEMENT VOUCHER — payment date, Paid To, source bank
//   cash-in   CASH RECEIPT VOUCHER      — received from, destination bank
//   accrual   JOURNAL VOUCHER           — liability/receivable recognition,
//                                         plus the Cross-Reference note that
//                                         appears once the accrual is settled
// ---------------------------------------------------------------------------
export function journalVoucherPDF(entry, {
  kind = 'accrual',
  accountName = (c) => c,
  projectName,
  counterparty,
  bankAccount,
  crossRef = null,
  preparedBy = 'Finance',
  approvedBy = '',
} = {}) {
  const doc = new jsPDF()

  const TITLES = {
    'cash-out': 'CASH DISBURSEMENT VOUCHER',
    'cash-in': 'CASH RECEIPT VOUCHER',
    accrual: 'JOURNAL VOUCHER',
  }
  const cash = kind === 'cash-out' || kind === 'cash-in'
  header(doc, TITLES[kind] || TITLES.accrual)

  const lines = entry.lines || []
  const totalDebit = lines.reduce((a, l) => a + (Number(l.debit) || 0), 0)
  const totalCredit = lines.reduce((a, l) => a + (Number(l.credit) || 0), 0)

  // The voucher number is the document's identity — bigger than anything else
  // on the page, because it is what the filing cabinet is indexed by.
  doc.setTextColor(...NAVY)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(15)
  doc.text(entry.voucherNo || entry.id, 16, 48)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(8)
  doc.setTextColor(...GREY)
  doc.text('VOUCHER NO.', 16, 53)

  doc.setTextColor(60, 60, 60)
  doc.setFontSize(9)
  doc.text(`Journal ref   ${entry.id}`, 16, 63)
  doc.text(`${cash ? 'Payment date' : 'Posting date'}  ${entry.date}`, 16, 69)
  doc.text(`Project ID    ${entry.project || '—'}`, 16, 75)
  doc.text(`Project       ${projectName || '—'}`, 16, 81)

  doc.text(`${kind === 'cash-in' ? 'Received from' : kind === 'cash-out' ? 'Paid to' : 'Counterparty'}   ${counterparty || '—'}`, 110, 63)
  if (cash) doc.text(`${kind === 'cash-in' ? 'Into account' : 'Source account'}  ${bankAccount || '—'}`, 110, 69)
  doc.text(`Memo          ${doc.splitTextToSize(entry.memo || '—', 78)[0]}`, 110, cash ? 75 : 69)

  // Status stamp. A reversed voucher must say so on its face — an unmarked
  // print of a reversed entry is a document that lies.
  const reversed = Boolean(entry.reversedBy)
  const stamp = reversed ? 'REVERSED' : entry.reversalOf ? 'REVERSAL' : cash ? 'PAID' : 'POSTED'
  const stampColor = reversed ? [200, 60, 60] : entry.reversalOf ? [150, 100, 180] : [40, 160, 100]
  doc.setDrawColor(...stampColor)
  doc.setTextColor(...stampColor)
  doc.setFontSize(13)
  doc.setFont('helvetica', 'bold')
  doc.roundedRect(146, 44, 48, 14, 2, 2)
  doc.text(stamp, 170, 53, { align: 'center' })
  doc.setFont('helvetica', 'normal')

  // Entry lines
  let y = 100
  doc.setFillColor(...NAVY)
  doc.setTextColor(255, 255, 255)
  doc.rect(16, y - 6, 178, 9, 'F')
  doc.setFontSize(9)
  doc.text('ACCOUNT & DESCRIPTION', 20, y)
  doc.text('DEBIT', 152, y, { align: 'right' })
  doc.text('CREDIT', 190, y, { align: 'right' })

  y += 10
  doc.setTextColor(60, 60, 60)
  lines.forEach((l) => {
    doc.setFontSize(9.5)
    doc.text(accountName(l.account), 20, y)
    doc.text(l.debit ? money2(l.debit) : '-', 152, y, { align: 'right' })
    doc.text(l.credit ? money2(l.credit) : '-', 190, y, { align: 'right' })
    if (l.note) {
      y += 4.4
      doc.setFontSize(7.5)
      doc.setTextColor(130, 130, 130)
      doc.text(doc.splitTextToSize(l.note, 120)[0], 24, y)
      doc.setTextColor(60, 60, 60)
    }
    y += 7
  })

  y += 2
  doc.setDrawColor(...NAVY)
  doc.setLineWidth(0.4)
  doc.line(16, y, 194, y)
  y += 8
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.text('TOTAL', 20, y)
  doc.text(money2(totalDebit), 152, y, { align: 'right' })
  doc.text(money2(totalCredit), 190, y, { align: 'right' })
  doc.setFont('helvetica', 'normal')

  // Cross-reference. The client asked that on settlement "the system
  // automatically embeds a Cross-Reference note" on the accrual document, so
  // whoever pulls the accrual out of the file can see how it was cleared.
  y += 12
  if (crossRef) {
    doc.setDrawColor(...GOLD)
    doc.setFillColor(253, 249, 240)
    doc.roundedRect(16, y, 178, 22, 2, 2, 'FD')
    doc.setFontSize(8)
    doc.setTextColor(150, 110, 30)
    doc.text('CROSS-REFERENCE', 22, y + 7)
    doc.setFontSize(9)
    doc.setTextColor(70, 70, 70)
    doc.text(
      doc.splitTextToSize(
        `Settled by voucher ${crossRef.voucherNo || crossRef.id} on ${crossRef.date}. ${crossRef.memo || ''}`.trim(),
        166
      )[0],
      22, y + 15
    )
    y += 30
  }

  // Three-way signature block: whoever wrote it, whoever authorised it, and
  // whoever took the money. That triple is the point of printing at all.
  y = Math.max(y, 232)
  doc.setDrawColor(120, 120, 120)
  doc.setLineWidth(0.2)
  const cols = [
    ['Prepared by', preparedBy],
    ['Approved by', approvedBy],
    [kind === 'cash-in' ? 'Received by' : kind === 'cash-out' ? 'Received by' : 'Acknowledged by', ''],
  ]
  cols.forEach(([label, who], i) => {
    const x = 20 + i * 60
    doc.line(x, y, x + 48, y)
    doc.setFontSize(8)
    doc.setTextColor(...GREY)
    doc.text(label, x, y + 5)
    if (who) {
      doc.setTextColor(...GOLD)
      doc.setFont('helvetica', 'italic')
      doc.setFontSize(11)
      doc.text(who, x + 4, y - 3)
      doc.setFont('helvetica', 'normal')
    }
  })

  footer(doc, reversed
    ? `This voucher was reversed by ${entry.reversedBy}. Retained for audit trail only.`
    : 'Posted entries cannot be deleted. Corrections are made by reversal and re-posting.')
  doc.save(`${(entry.voucherNo || entry.id).replace(/[^A-Za-z0-9]+/g, '_')}.pdf`)
}

