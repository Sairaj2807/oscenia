// ---------------------------------------------------------------------------
// Project P&L statement (phase 6)
// ---------------------------------------------------------------------------
export function pnlPDF({ heading, revenue, rows, grossProfit, margin }) {
  const doc = new jsPDF()
  header(doc, 'PROFIT & LOSS')

  doc.setTextColor(60, 60, 60)
  doc.setFontSize(10)
  doc.text(`Statement    ${heading}`, 16, 48)
  doc.text(`Generated    ${new Date().toISOString().slice(0, 10)}`, 16, 55)

  let y = 76
  doc.setFillColor(...NAVY)
  doc.setTextColor(255, 255, 255)
  doc.rect(16, y - 6, 178, 9, 'F')
  doc.setFontSize(9)
  doc.text('LINE', 20, y)
  doc.text('AMOUNT (IDR)', 190, y, { align: 'right' })

  y += 12
  doc.setTextColor(60, 60, 60)
  doc.setFontSize(10)
  doc.text('Revenue recognised', 20, y)
  doc.text(money(revenue), 190, y, { align: 'right' })
  y += 10

  rows.forEach((r) => {
    doc.text(`  ${r.label}`, 20, y)
    doc.text(`(${money(r.amount)})`, 190, y, { align: 'right' })
    y += 8
  })

  y += 4
  doc.setDrawColor(220, 220, 220)
  doc.line(16, y, 194, y)
  y += 10
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(12)
  doc.text('GROSS PROJECT PROFIT', 20, y)
  doc.setTextColor(...GOLD)
  doc.text(money(grossProfit), 190, y, { align: 'right' })
  y += 8
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(60, 60, 60)
  doc.setFontSize(9)
  doc.text(`Margin ${margin.toFixed(2)}%`, 190, y, { align: 'right' })

  footer(doc, 'Figures derived from posted journal entries in the Oscenia general ledger.')
  doc.save(`PnL_${heading.replace(/[^A-Za-z0-9]+/g, '_')}.pdf`)
}
